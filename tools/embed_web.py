#!/usr/bin/env python3
"""Embed local assets; never load external resources on the device."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
html=(root/'web/index.html').read_text()
js=(root/'web/app.js').read_text()
html=html.replace('<script src="protocol.js"></script>', '<script>'+(root/'web/protocol.js').read_text()+'</script>')
html=html.replace('<script src="map.js"></script>', '<script>'+(root/'web/map.js').read_text()+'</script>')
html=html.replace('<script src="app.js"></script>','<script>'+js+'</script>')
assert ')DRPAGE"' not in html
p=root/'firmware/MeshCore/examples/companion_radio/PortalPage.h'
p.write_text('// Generated by tools/embed_web.py\n#pragma once\n#include <Arduino.h>\nstatic const char PORTAL_PAGE[] PROGMEM = R"DRPAGE('+html+')DRPAGE";\n')
print(f'Embedded {len(html.encode())} bytes into {p.name}')
