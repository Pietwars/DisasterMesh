#!/usr/bin/env python3
"""Embed local assets; never load external resources on the device."""
from pathlib import Path
from web_assets import inline_theme
root=Path(__file__).resolve().parents[1]
html=inline_theme((root/'web/index.html').read_text(encoding='utf-8'))
js=(root/'web/app.js').read_text(encoding='utf-8')
html=html.replace('<script src="protocol.js"></script>', '<script>'+(root/'web/protocol.js').read_text(encoding='utf-8')+'</script>')
html=html.replace('<script src="map.js"></script>', '<script>'+(root/'web/map.js').read_text(encoding='utf-8')+'</script>')
html=html.replace('<script src="map-library.js"></script>', '<script>'+(root/'web/map-library.js').read_text(encoding='utf-8')+'</script>')
html=html.replace('<script src="poi.js"></script>', '<script>'+(root/'web/poi.js').read_text(encoding='utf-8')+'</script>')
html=html.replace('<script src="app.js"></script>','<script>'+js+'</script>')
assert ')DRPAGE"' not in html
p=root/'firmware/MeshCore/examples/companion_radio/PortalPage.h'
p.write_text('// Generated by tools/embed_web.py\n#pragma once\n#include <Arduino.h>\nstatic const char PORTAL_PAGE[] PROGMEM = R"DRPAGE('+html+')DRPAGE";\n', encoding='utf-8', newline='\n')
print(f'Embedded {len(html.encode())} bytes into {p.name}')

manifest=(root/'web/app.webmanifest').read_text(encoding='utf-8')
icon=(root/'web/app-icon.png').read_bytes()
(root/'firmware/MeshCore/examples/companion_radio/PortalAssets.h').write_text(
    '// Generated by tools/embed_web.py\n#pragma once\n#include <Arduino.h>\n'
    +'static const char PORTAL_MANIFEST[] PROGMEM = R"ASSET('+manifest+')ASSET";\n'
    +'static const uint8_t PORTAL_ICON[] PROGMEM = {'+','.join(str(b) for b in icon)+'};\n', encoding='utf-8')
